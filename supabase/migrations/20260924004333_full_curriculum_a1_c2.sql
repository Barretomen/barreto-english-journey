    'clinics', coalesce((select jsonb_agg(jsonb_build_object(
      'id', c.id, 'external_id', c.external_id, 'level_code', c.level_code,
      'title', c.title, 'focus', c.focus, 'why', c.why_text, 'examples', c.examples,
      'recycle_in', c.recycle_in, 'visual_external_id', c.visual_external_id,
      'exercises', coalesce((select jsonb_agg(jsonb_build_object(
