create or replace function public.import_private_answer_keys(p_entries jsonb)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare entry record; imported integer := 0;
begin
  if (select auth.role()) <> 'service_role' then
    raise exception 'service_role_required' using errcode = '42501';
  end if;
  for entry in select key, value from jsonb_each(p_entries) loop
    insert into private.answer_keys (
      external_id, expected_answer, accepted_answers, model_answer, rationale, rubric, source_metadata, updated_at
    ) values (
      entry.key,
      entry.value -> 'answer',
      entry.value -> 'accepted',
      entry.value ->> 'model_answer',
      entry.value ->> 'rationale',
      entry.value -> 'rubric',
      entry.value - array['answer','accepted','model_answer','rationale','rubric'],
      now()
    ) on conflict (external_id) do update set
      expected_answer = excluded.expected_answer,
      accepted_answers = excluded.accepted_answers,
      model_answer = excluded.model_answer,
      rationale = excluded.rationale,
      rubric = excluded.rubric,
      source_metadata = excluded.source_metadata,
      updated_at = now();
    imported := imported + 1;
  end loop;
  return imported;
end;
$$;

drop function if exists public.get_admin_audio_overview();
create function public.get_admin_audio_overview()
returns table (
  lesson_id bigint, level_code text, module_id bigint, module_title text,
  lesson_number integer, title text, ready_count bigint, missing_count bigint,
  generating_count bigint, failed_count bigint, total_count bigint
)
language plpgsql
stable
security invoker
set search_path = ''
as $$
begin
  if not private.is_admin() then raise exception 'admin_required' using errcode = '42501'; end if;
  return query select l.id, m.level_code, m.id, m.title, l.level_lesson_number, l.title,
    count(b.id) filter (where b.audio_status = 'ready'),
    count(b.id) filter (where b.audio_status = 'missing'),
    count(b.id) filter (where b.audio_status = 'generating'),
    count(b.id) filter (where b.audio_status = 'failed'), count(b.id)
  from public.lessons l join public.modules m on m.id = l.module_id
  left join public.lesson_blocks b on b.lesson_id = l.id and b.audio_required
  where l.published and not l.is_legacy
  group by l.id, m.level_code, m.id, m.title, l.level_lesson_number, l.title, l.global_order
  order by l.global_order;
end;
$$;

