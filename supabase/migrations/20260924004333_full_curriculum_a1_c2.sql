  select jsonb_build_object(
    'due_reviews', coalesce((select jsonb_agg(jsonb_build_object(
      'id', r.id, 'lesson_id', r.lesson_id, 'lesson_title', l.title,
      'level_code', m.level_code, 'due_at', r.due_at, 'offset_days', r.review_offset_days
    ) order by r.due_at) from public.review_schedule r
      join public.lessons l on l.id = r.lesson_id join public.modules m on m.id = l.module_id
