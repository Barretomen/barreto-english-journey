create or replace function public.submit_exercise_attempt(p_exercise_id bigint, p_answer jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  key_external_id text;
  expected_answer jsonb;
  accepted_answers jsonb;
  answer_rationale text;
  target_lesson_id bigint;
  mode text;
  is_correct boolean := false;
  correct_message text;
  incorrect_message text;
  answer_text text;
begin
  select b.lesson_id, e.grading_mode, e.feedback_correct, e.feedback_incorrect,
    k.external_id, k.expected_answer, k.accepted_answers, k.rationale
  into target_lesson_id, mode, correct_message, incorrect_message,
    key_external_id, expected_answer, accepted_answers, answer_rationale
  from public.exercises e
  join public.lesson_blocks b on b.id = e.lesson_block_id
  left join private.answer_keys k on k.external_id = e.external_id
  where e.id = p_exercise_id;

  if target_lesson_id is null or not private.can_access_lesson(target_lesson_id) then
    raise exception 'exercise_not_accessible' using errcode = '42501';
  end if;
  if p_answer is null or p_answer = 'null'::jsonb then
    raise exception 'answer_required' using errcode = '22023';
  end if;

  if mode = 'subjective' then
    insert into public.exercise_attempts (student_id, exercise_id, answer, correct, submission_status)
    values ((select auth.uid()), p_exercise_id, p_answer, null, 'submitted');
    return jsonb_build_object(
      'correct', null, 'submitted', true,
      'message', 'Resposta enviada. Ela foi registrada para revisão.',
      'explanation', 'Atividades abertas não recebem uma nota automática.'
    );
  end if;

  if key_external_id is null then
    raise exception 'answer_key_missing' using errcode = 'P0002';
  end if;
  answer_text := lower(trim(p_answer #>> '{}'));
  is_correct := (
    expected_answer is not null
    and lower(trim(expected_answer #>> '{}')) = answer_text
  ) or exists (
    select 1 from jsonb_array_elements_text(coalesce(accepted_answers, '[]'::jsonb)) candidate
    where lower(trim(candidate)) = answer_text
  );

  insert into public.exercise_attempts (student_id, exercise_id, answer, correct, submission_status)
  values ((select auth.uid()), p_exercise_id, p_answer, is_correct, 'graded');
  return jsonb_build_object(
    'correct', is_correct, 'submitted', true,
    'message', case when is_correct then correct_message else incorrect_message end,
    'explanation', case when is_correct then 'Muito bem. Continue avançando.' else coalesce(answer_rationale, 'Revise o exemplo e tente novamente.') end
  );
end;
$$;

create or replace function public.complete_lesson(p_lesson_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  total_exercises integer;
  submitted_exercises integer;
  graded_exercises integer;
  correct_answers integer;
  score_percent integer;
  reward integer;
  checkpoint boolean;
  next_lesson_id bigint;
  current_order integer;
  next_level text;
  awarded integer := 0;
begin
  if not private.can_access_lesson(p_lesson_id) then
    raise exception 'lesson_not_accessible' using errcode = '42501';
  end if;
  select l.xp_reward, l.is_checkpoint, l.global_order into reward, checkpoint, current_order
  from public.lessons l where l.id = p_lesson_id and l.published and not l.is_legacy;
  if current_order is null then raise exception 'lesson_not_found' using errcode = 'P0002'; end if;

  select count(*)::integer,
    count(*) filter (where e.grading_mode = 'automatic')::integer
  into total_exercises, graded_exercises
  from public.exercises e join public.lesson_blocks b on b.id = e.lesson_block_id
  where b.lesson_id = p_lesson_id;

  select count(*)::integer into submitted_exercises from (
    select distinct a.exercise_id
    from public.exercise_attempts a
    join public.exercises e on e.id = a.exercise_id
    join public.lesson_blocks b on b.id = e.lesson_block_id
    where a.student_id = (select auth.uid()) and b.lesson_id = p_lesson_id
  ) submitted;
  if submitted_exercises < total_exercises then
    raise exception 'lesson_exercises_incomplete' using errcode = 'P0001';
  end if;

  select count(*)::integer into correct_answers from (
    select distinct a.exercise_id
    from public.exercise_attempts a
    join public.exercises e on e.id = a.exercise_id
    join public.lesson_blocks b on b.id = e.lesson_block_id
    where a.student_id = (select auth.uid()) and b.lesson_id = p_lesson_id
      and e.grading_mode = 'automatic' and a.correct
  ) correct;
  score_percent := case when graded_exercises = 0 then 100
    else round((correct_answers::numeric / graded_exercises) * 100)::integer end;
  reward := reward
    + case when graded_exercises > 0 and correct_answers = graded_exercises then 20 else 0 end
    + case when checkpoint then 50 else 0 end;

  insert into public.lesson_progress
    (student_id, lesson_id, status, current_position, score_percent, started_at, completed_at, updated_at)
  values ((select auth.uid()), p_lesson_id, 'completed', 0, score_percent, now(), now(), now())
  on conflict (student_id, lesson_id) do update set
    status = 'completed', score_percent = greatest(coalesce(public.lesson_progress.score_percent, 0), excluded.score_percent),
    completed_at = coalesce(public.lesson_progress.completed_at, now()), updated_at = now();

  insert into public.xp_events (student_id, points, event_type, source_id)
  values ((select auth.uid()), reward, 'lesson_completed', p_lesson_id)
  on conflict (student_id, event_type, source_id) where source_id is not null do nothing;
  if found then awarded := reward; end if;

  insert into public.review_schedule (student_id, lesson_id, review_offset_days, due_at)
  select (select auth.uid()), p_lesson_id, days, now() + make_interval(days => days)
  from unnest(array[1,3,7,21]) days
  on conflict (student_id, lesson_id, review_offset_days) do nothing;

  select l.id, m.level_code into next_lesson_id, next_level
  from public.lessons l join public.modules m on m.id = l.module_id
  where l.published and not l.is_legacy and l.global_order > current_order
  order by l.global_order limit 1;
  if next_lesson_id is not null then
    insert into public.student_lesson_access (student_id, lesson_id, unlocked)
    values ((select auth.uid()), next_lesson_id, true)
    on conflict (student_id, lesson_id) do update set unlocked = true, unlocked_at = now();
    update public.profiles set current_level_code = next_level, updated_at = now()
    where id = (select auth.uid());
  else
    update public.profiles set course_completed_at = coalesce(course_completed_at, now()), updated_at = now()
    where id = (select auth.uid());
  end if;

  return jsonb_build_object(
    'correct_answers', correct_answers, 'total_exercises', graded_exercises,
    'submitted_exercises', submitted_exercises, 'score_percent', score_percent,
    'xp_awarded', awarded, 'next_lesson_id', next_lesson_id,
    'course_completed', next_lesson_id is null
  );
end;
$$;

create or replace function public.get_dashboard_metrics()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  with activity_dates as (
    select distinct activity_at::date activity_date from (
      select a.attempted_at activity_at from public.exercise_attempts a where a.student_id = (select auth.uid())
      union all
      select p.completed_at from public.lesson_progress p where p.student_id = (select auth.uid()) and p.completed_at is not null
    ) activities
  ), numbered as (
    select activity_date, activity_date - row_number() over (order by activity_date)::integer grp from activity_dates
  ), streaks as (
    select min(activity_date) start_date, max(activity_date) end_date, count(*)::integer days
    from numbered group by grp
  )
  select jsonb_build_object(
    'xp', coalesce((select sum(x.points) from public.xp_events x where x.student_id = (select auth.uid())), 0),
    'completed_lessons', (select count(*) from public.lesson_progress p join public.lessons l on l.id = p.lesson_id
      where p.student_id = (select auth.uid()) and p.status = 'completed' and not l.is_legacy),
    'streak', coalesce((select days from streaks
      where end_date in (current_date, current_date - 1) order by end_date desc limit 1), 0)
  )
$$;

