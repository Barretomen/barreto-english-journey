  ) then raise exception 'clinic_exercise_not_accessible' using errcode = '42501'; end if;
  insert into public.grammar_clinic_submissions (student_id, exercise_id, answer)
  values ((select auth.uid()), p_exercise_id, p_answer);
  return jsonb_build_object('submitted', true, 'message', 'Resposta registrada para revisão.');
end;
$$;

