create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  )
$$;

create or replace function private.can_access_lesson(p_lesson_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null and (
    private.is_admin()
    or exists (
      select 1
      from public.student_lesson_access
      where student_id = (select auth.uid())
        and lesson_id = p_lesson_id
        and unlocked
    )
  )
$$;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  base_username text;
  final_username text;
begin
  base_username := lower(regexp_replace(
    coalesce(nullif(new.raw_user_meta_data ->> 'username', ''), split_part(coalesce(new.email, 'student'), '@', 1)),
    '[^a-z0-9._-]', '', 'g'
  ));
  if length(base_username) < 3 then
    base_username := 'student';
  end if;

  final_username := left(base_username, 31);
  if exists (select 1 from public.profiles where lower(username) = lower(final_username)) then
    final_username := left(base_username, 22) || '-' || left(new.id::text, 8);
  end if;

  insert into public.profiles (id, username, display_name, role, current_level_code)
  values (
    new.id,
    final_username,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), initcap(replace(final_username, '.', ' '))),
    'student',
    'A1'
  );

  insert into public.student_lesson_access (student_id, lesson_id, unlocked)
  select new.id, id, true from public.lessons
  where published
  order by position
  limit 1;

  return new;
end;
$$;

