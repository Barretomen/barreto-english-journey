create or replace function public.get_lesson_catalog()
returns table (
  id bigint,
  level_code text,
  module_title text,
  week_number integer,
  title text,
  summary text,
  state text,
  is_checkpoint boolean,
  progress_percent integer
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    l.id,
    m.level_code,
    m.title,
    l.week_number,
    l.title,
    l.summary,
    case
      when p.status = 'completed' then 'completed'
      when a.unlocked and p.status = 'in_progress' then 'current'
      when a.unlocked then 'available'
      when l.is_checkpoint then 'checkpoint'
      else 'locked'
    end,
    l.is_checkpoint,
    coalesce(
      case
        when p.status = 'completed' then 100
        when blocks.total_blocks > 0 then round((p.current_position::numeric / blocks.total_blocks) * 100)::integer
        else 0
      end,
      0
    )
  from public.lessons l
  join public.modules m on m.id = l.module_id
  left join public.student_lesson_access a
    on a.lesson_id = l.id and a.student_id = (select auth.uid()) and a.unlocked
  left join public.lesson_progress p
    on p.lesson_id = l.id and p.student_id = (select auth.uid())
  left join lateral (
    select count(*)::integer as total_blocks
    from public.lesson_blocks b
    where b.lesson_id = l.id
  ) blocks on true
  where l.published
  order by l.position
$$;

create or replace function public.save_lesson_position(p_lesson_id bigint, p_position integer)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.can_access_lesson(p_lesson_id) then
    raise exception 'lesson_not_accessible' using errcode = '42501';
  end if;

  insert into public.lesson_progress
    (student_id, lesson_id, status, current_position, started_at, updated_at)
  values
    ((select auth.uid()), p_lesson_id, 'in_progress', greatest(p_position, 0), now(), now())
  on conflict (student_id, lesson_id) do update
    set status = case when public.lesson_progress.status = 'completed' then 'completed' else 'in_progress' end,
        current_position = greatest(public.lesson_progress.current_position, excluded.current_position),
        started_at = coalesce(public.lesson_progress.started_at, now()),
        updated_at = now();
end;
$$;

create or replace function public.submit_exercise_attempt(p_exercise_id bigint, p_answer jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  expected jsonb;
  target_lesson_id bigint;
  is_correct boolean := false;
  correct_message text;
  incorrect_message text;
begin
  select a.expected_answer, b.lesson_id, e.feedback_correct, e.feedback_incorrect
  into expected, target_lesson_id, correct_message, incorrect_message
  from private.exercise_answers a
  join public.exercises e on e.id = a.exercise_id
  join public.lesson_blocks b on b.id = e.lesson_block_id
  where a.exercise_id = p_exercise_id;

  if expected is null or not private.can_access_lesson(target_lesson_id) then
    raise exception 'exercise_not_accessible' using errcode = '42501';
  end if;

  if jsonb_typeof(expected) = 'array' then
    select exists (
      select 1 from jsonb_array_elements_text(expected) candidate
      where lower(trim(candidate)) = lower(trim(p_answer #>> '{}'))
    ) into is_correct;
  else
    is_correct := lower(trim(expected #>> '{}')) = lower(trim(p_answer #>> '{}'));
  end if;

  insert into public.exercise_attempts (student_id, exercise_id, answer, correct)
  values ((select auth.uid()), p_exercise_id, p_answer, is_correct);

  return jsonb_build_object(
    'correct', is_correct,
    'message', case when is_correct then correct_message else incorrect_message end,
    'explanation', case when is_correct then 'Muito bem. Continue avançando.' else 'Revise o exemplo e tente novamente.' end
  );
end;
$$;

create or replace function public.complete_lesson(p_lesson_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  total_exercises integer;
  correct_answers integer;
  score_percent integer;
  reward integer;
  checkpoint boolean;
  next_lesson_id bigint;
begin
  if not private.can_access_lesson(p_lesson_id) then
    raise exception 'lesson_not_accessible' using errcode = '42501';
  end if;

  select l.xp_reward, l.is_checkpoint into reward, checkpoint
  from public.lessons l where l.id = p_lesson_id;

  select count(*)::integer into total_exercises
  from public.exercises e
  join public.lesson_blocks b on b.id = e.lesson_block_id
  where b.lesson_id = p_lesson_id;

  select count(distinct a.exercise_id)::integer into correct_answers
  from public.exercise_attempts a
  join public.exercises e on e.id = a.exercise_id
  join public.lesson_blocks b on b.id = e.lesson_block_id
  where a.student_id = (select auth.uid())
    and b.lesson_id = p_lesson_id
    and a.correct;

  score_percent := case when total_exercises = 0 then 100 else round((correct_answers::numeric / total_exercises) * 100)::integer end;
  reward := reward
    + case when total_exercises > 0 and correct_answers = total_exercises then 20 else 0 end
    + case when checkpoint then 50 else 0 end;

  insert into public.lesson_progress
    (student_id, lesson_id, status, current_position, score_percent, started_at, completed_at, updated_at)
  values
    ((select auth.uid()), p_lesson_id, 'completed', 0, score_percent, now(), now(), now())
  on conflict (student_id, lesson_id) do update
    set status = 'completed',
        score_percent = greatest(coalesce(public.lesson_progress.score_percent, 0), excluded.score_percent),
        completed_at = coalesce(public.lesson_progress.completed_at, now()),
        updated_at = now();

  insert into public.xp_events (student_id, points, event_type, source_id)
  values ((select auth.uid()), reward, 'lesson_completed', p_lesson_id)
  on conflict (student_id, event_type, source_id) where source_id is not null do nothing;

  select next_lesson.id into next_lesson_id
  from public.lessons current_lesson
  join public.lessons next_lesson on next_lesson.position > current_lesson.position and next_lesson.published
  where current_lesson.id = p_lesson_id
  order by next_lesson.position
  limit 1;

  if next_lesson_id is not null then
    insert into public.student_lesson_access (student_id, lesson_id, unlocked)
    values ((select auth.uid()), next_lesson_id, true)
    on conflict (student_id, lesson_id) do update set unlocked = true, unlocked_at = now();
  end if;

  return jsonb_build_object(
    'correct_answers', correct_answers,
    'total_exercises', total_exercises,
    'score_percent', score_percent,
    'xp_awarded', reward
  );
end;
$$;

create or replace function public.get_admin_student_overview()
returns table (
  id uuid,
  display_name text,
  username text,
  level_code text,
  progress_percent integer,
  accuracy_percent integer,
  xp bigint,
  last_activity timestamptz,
  completed_lessons bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not private.is_admin() then
    raise exception 'admin_required' using errcode = '42501';
  end if;

  return query
  select
    p.id,
    p.display_name,
    p.username,
    p.current_level_code,
    coalesce(round(100.0 * count(lp.lesson_id) filter (where lp.status = 'completed') / nullif((select count(*) from public.lessons where published), 0))::integer, 0),
    coalesce(round(100.0 * count(ea.id) filter (where ea.correct) / nullif(count(ea.id), 0))::integer, 0),
    coalesce((select sum(x.points) from public.xp_events x where x.student_id = p.id), 0),
    max(ea.attempted_at),
    count(distinct lp.lesson_id) filter (where lp.status = 'completed')
  from public.profiles p
  left join public.lesson_progress lp on lp.student_id = p.id
  left join public.exercise_attempts ea on ea.student_id = p.id
  where p.role = 'student'
  group by p.id, p.display_name, p.username, p.current_level_code;
end;
$$;

create or replace function public.admin_unlock_lesson(p_student_id uuid, p_lesson_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_admin() then
    raise exception 'admin_required' using errcode = '42501';
  end if;
  insert into public.student_lesson_access (student_id, lesson_id, unlocked, unlocked_by)
  values (p_student_id, p_lesson_id, true, (select auth.uid()))
  on conflict (student_id, lesson_id) do update
    set unlocked = true, unlocked_at = now(), unlocked_by = (select auth.uid());
end;
$$;

