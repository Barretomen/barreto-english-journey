-- English Journey: clean rebuild of the reusable Supabase project.
-- The previous public schema belonged to an unrelated application.

drop schema if exists public cascade;
create schema public authorization postgres;
comment on schema public is 'Barreto English Journey API';

grant usage on schema public to postgres, anon, authenticated, service_role;
grant all on schema public to postgres, service_role;

-- Remove accounts from the previous application. The project owner explicitly
-- authorized full reuse of this Supabase project.
delete from auth.users;

create schema if not exists private authorization postgres;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated, service_role;

alter default privileges for role postgres in schema public
  revoke select, insert, update, delete on tables from anon, authenticated;
alter default privileges for role postgres in schema public
  revoke usage, select on sequences from anon, authenticated;
alter default privileges for role postgres in schema public
  revoke execute on functions from public, anon, authenticated;

create table public.levels (
  code text primary key check (code in ('A1', 'A2')),
  title text not null,
  position integer not null unique check (position > 0)
);

create table public.modules (
  id bigint generated by default as identity primary key,
  level_code text not null references public.levels(code) on update cascade on delete restrict,
  title text not null,
  position integer not null unique check (position > 0)
);

create table public.lessons (
  id bigint generated by default as identity primary key,
  module_id bigint not null references public.modules(id) on delete cascade,
  lesson_number integer not null unique check (lesson_number > 0),
  week_number integer,
  title text not null,
  summary text not null default '',
  xp_reward integer not null default 50 check (xp_reward >= 0),
  is_checkpoint boolean not null default false,
  published boolean not null default false,
  position integer not null unique check (position > 0),
  created_at timestamptz not null default now()
);

create table public.lesson_blocks (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  block_type text not null check (block_type in (
    'text', 'vocabulary', 'grammar', 'example', 'multiple_choice',
    'fill_blank', 'reorder_words', 'true_false', 'listening',
    'speaking', 'reading', 'writing', 'checkpoint'
  )),
  position integer not null check (position > 0),
  title text,
  content jsonb not null default '{}'::jsonb,
  unique (lesson_id, position)
);

create table public.exercises (
  id bigint generated by default as identity primary key,
  lesson_block_id bigint not null unique references public.lesson_blocks(id) on delete cascade,
  exercise_type text not null,
  prompt text not null,
  instruction text,
  content jsonb not null default '{}'::jsonb,
  feedback_correct text not null,
  feedback_incorrect text not null
);

create table private.exercise_answers (
  exercise_id bigint primary key references public.exercises(id) on delete cascade,
  expected_answer jsonb not null
);

create table public.exercise_options (
  id bigint generated by default as identity primary key,
  exercise_id bigint not null references public.exercises(id) on delete cascade,
  label text not null,
  value text not null,
  position integer not null check (position > 0),
  unique (exercise_id, position)
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (username = lower(username) and username ~ '^[a-z0-9._-]{3,40}$'),
  display_name text not null check (length(trim(display_name)) between 1 and 80),
  role text not null default 'student' check (role in ('student', 'admin')),
  current_level_code text not null default 'A1' references public.levels(code),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index profiles_username_lower_idx on public.profiles (lower(username));

create table public.student_lesson_access (
  student_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  unlocked boolean not null default true,
  unlocked_at timestamptz not null default now(),
  unlocked_by uuid references public.profiles(id) on delete set null,
  primary key (student_id, lesson_id)
);

create table public.lesson_progress (
  student_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  status text not null default 'not_started' check (status in ('not_started', 'in_progress', 'completed')),
  current_position integer not null default 0 check (current_position >= 0),
  score_percent integer check (score_percent between 0 and 100),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (student_id, lesson_id)
);

create table public.exercise_attempts (
